import {locale,setLocale} from './locale.js';
import enDashboard from '../locales/en/dashboard.json';
import knDashboard from '../locales/kn/dashboard.json';
import i18n from 'i18next';
import {initReactI18next} from 'react-i18next';
import enCommon from '../locales/en/common.json';
import knCommon from '../locales/kn/common.json';
import enSettings from '../locales/en/settings.json';
import knSettings from '../locales/kn/settings.json';
import enNavigation from '../locales/en/navigation.json';
import knNavigation from '../locales/kn/navigation.json';
i18n.use(initReactI18next).init({resources:{en:{common:enCommon,settings:enSettings,navigation:enNavigation,dashboard:enDashboard},kn:{common:knCommon,settings:knSettings,navigation:knNavigation,dashboard:knDashboard}},lng:'en',fallbackLng:'en',supportedLngs:['en','kn'],defaultNS:'common',interpolation:{escapeValue:false},initImmediate:false});
i18n.on('languageChanged',language=>{setLocale(language);document.documentElement.lang=language;});
document.documentElement.lang='en';
export {locale};
export const formatDate=(value,options={})=>new Intl.DateTimeFormat(locale(),{timeZone:'Asia/Kolkata',...options}).format(new Date(value));
export const formatNumber=(value,options={})=>new Intl.NumberFormat(locale(),options).format(value);
export const formatMoney=(value,currency='INR')=>formatNumber(value,{style:'currency',currency,maximumFractionDigits:0});
export default i18n;
